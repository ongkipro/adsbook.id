// Writes src/migrations.generated.ts: the checked-in chain 0000…0079 as a
// module, plus two spike-only files used to probe the migration protocol.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../../../src/db/migrations/", import.meta.url);
const chain = readdirSync(dir)
  .filter((name) => name.endsWith(".sql"))
  .sort()
  .map((name) => ({ name, sql: readFileSync(new URL(name, dir), "utf8") }));

const probe = [
  { name: "0080_spike_probe.sql", sql: "CREATE TABLE spike_probe (id INTEGER PRIMARY KEY, note TEXT NOT NULL);" },
  { name: "0081_spike_fail.sql", sql: "CREATE TABLE spike_fail_ok (id INTEGER PRIMARY KEY);\nINSERT INTO no_such_table (x) VALUES (1);" },
];

writeFileSync(
  new URL("../src/migrations.generated.ts", import.meta.url),
  `// Generated by scripts/gen-migrations.mjs. Do not edit.\nimport type { MigrationFile } from "./store-core.ts";\n\nexport const CHAIN: readonly MigrationFile[] = ${JSON.stringify(chain)};\n\nexport const PROBE: readonly MigrationFile[] = ${JSON.stringify(probe)};\n`,
);
console.log(`chain ${chain.length} files, probe ${probe.length}`);
